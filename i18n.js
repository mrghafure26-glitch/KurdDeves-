const LANGUAGE_STORAGE_KEY = 'lang';
const DEFAULT_LANG = 'en';

let currentLang = DEFAULT_LANG;

/* Look up a translation key for the active language (falls back to EN, then the key itself) */
function t(key) {
    const dict = translations[currentLang] || translations.en;
    if (dict && dict[key] != null) return dict[key];
    if (translations.en && translations.en[key] != null) return translations.en[key];
    return key;
}

function applyLanguage(lang) {
    if (!translations[lang]) lang = DEFAULT_LANG;
    currentLang = lang;

    /* Set <html lang> + text direction for the whole document */
    document.documentElement.setAttribute('lang', lang);
    document.documentElement.setAttribute('dir', lang === 'ku' ? 'rtl' : 'ltr');
    document.title = t('meta.title');

    /* Translate all [data-i18n] visible text */
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (!key || !translations.en[key]) return;
        const text = t(key);
        if (el.hasAttribute('data-i18n-html')) {
            el.innerHTML = text;
        } else {
            el.textContent = text;
        }
    });

    /* Translate placeholders */
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (key && translations.en[key]) {
            el.setAttribute('placeholder', t(key));
        }
    });

    /* Translate aria-labels */
    document.querySelectorAll('[data-i18n-aria]').forEach(el => {
        const key = el.getAttribute('data-i18n-aria');
        if (key && translations.en[key]) {
            el.setAttribute('aria-label', t(key));
        }
    });

    /* Keep both toggle buttons in sync */
    const isKu = lang === 'ku';
    document.querySelectorAll('.language-switch').forEach(btn => {
        btn.classList.toggle('is-active', isKu);
        btn.setAttribute('aria-pressed', String(isKu));
        btn.setAttribute('aria-label', isKu ? t('lang.switchToEn') : t('lang.switchToKu'));
    });

    /* Persist the choice so it survives a page refresh */
    try {
        localStorage.setItem(LANGUAGE_STORAGE_KEY, lang);
    } catch (e) { }
}

/* Restore the saved language on load */
applyLanguage(localStorage.getItem(LANGUAGE_STORAGE_KEY) || DEFAULT_LANG);

/* Toggle EN <-> KU on click */
document.querySelectorAll('.language-switch').forEach(button => {
    button.addEventListener('click', () => {
        applyLanguage(currentLang === 'ku' ? 'en' : 'ku');
    });
});
